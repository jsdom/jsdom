import context from "../lib/jsdom/living/css/parse/context.js";
import definitions from "../lib/generated/css-property-definitions.js";
import fs from "node:fs/promises";
import { generateCSSModule } from "./generate-css-module.mjs";
import parser from "../lib/jsdom/living/css/parse/parser.js";
import path from "node:path";
import serialize from "../lib/jsdom/living/css/serialize.js";
import values from "../lib/jsdom/living/css/values/value.js";

const initialValues = {};
for (const [name, { initial }] of Object.entries(definitions)) {
  if (initial === undefined) {
    continue;
  }
  if (initial === null) {
    initialValues[name] = null;
    continue;
  }
  const value = parser.parseDeclarationValue(initial, name, context.createVirtualContext({}, "@style"));
  if (values.isFailure(value)) {
    throw new Error(`Invalid initial value for ${name}: ${initial}`, {
      cause: values.isParseErrorInfo(value) ? new SyntaxError(value.message) : value
    });
  }
  const serialized = serialize.serializeDeclarationValue({ name, value });
  definitions[name].initial = serialized;
  initialValues[name] = value;
}

// The first build phase supplies webref's initial spellings to the parser.
// Replace them with canonical strings for shorthand serialization at runtime.
await fs.writeFile(
  path.resolve(import.meta.dirname, "../lib/generated/css-property-definitions.js"),
  '"use strict";\n\n// Generated by scripts/generate-css-data.mjs from @webref/css and patched CSSTree data; ' +
  "initial values normalized by scripts/generate-css-initial-values.mjs.\n" +
  `module.exports = ${JSON.stringify(definitions)};\n`
);

const output = generateCSSModule(
  initialValues,
  "generated/css-property-definitions.js by scripts/generate-css-initial-values.mjs"
);
await fs.writeFile(path.resolve(import.meta.dirname, "../lib/generated/css-initial-values.js"), output);

import compatibility from "../lib/jsdom/living/css/compatibility.js";
import definitionsModule from "../lib/jsdom/living/css/rules/definitions.js";
import fs from "node:fs/promises";
import path from "node:path";
import stringUtils from "../lib/jsdom/living/css/utils/string.js";

const { toIDLAttribute } = stringUtils;
const { value: { rules } } = definitionsModule;
const outputDirectory = path.resolve(import.meta.dirname, "../lib/generated/css-webidl");
await fs.mkdir(outputDirectory, { recursive: true });
function findRule(name) {
  return rules.find(rule => rule.name === name);
}
const page = findRule("@page");
const definitions = [
  ["CSSFontFaceDescriptors", findRule("@font-face")],
  ["CSSFunctionDescriptors", findRule("@function")],
  ["CSSMarginDescriptors", page.value.rules.find(rule => rule.name === "@margin")],
  ["CSSPageDescriptors", page],
  ["CSSPositionTryDescriptors", findRule("@position-try")],
  ["CSSStyleProperties", findRule("@style")]
];
const reserved = new Set("any bigint boolean byte double float long object octet short symbol undefined".split(" "));

function namesWithAliases(properties, aliases) {
  return [
    ...Object.keys(properties).filter(name => !name.includes("*")),
    ...aliases?.aliases?.keys() ?? [],
    ...aliases?.mappings?.keys() ?? []
  ].filter(name => {
    return properties[name] || properties[aliases?.aliases?.get(name)] || properties[aliases?.mappings?.get(name)];
  });
}

for (const [interfaceName, rule] of definitions) {
  const names = [];
  if (rule.value.descriptors) {
    names.push(...namesWithAliases(rule.value.descriptors, compatibility.descriptors[rule.name]));
  }
  if (rule.value.properties) {
    names.push(...namesWithAliases(rule.value.properties, compatibility.properties));
  }
  const attributes = [];
  for (const name of names) {
    const variants = new Set([name]);
    if (name.includes("-")) {
      variants.add(toIDLAttribute(name));
      if (name.startsWith("-webkit-")) {
        variants.add(toIDLAttribute(name, true));
      }
    }
    for (const variant of variants) {
      const attribute = reserved.has(variant) ? `_${variant}` : variant;
      const extendedAttributes = `[CEReactions, ReflectStyle="${name}"]`;
      attributes.push(`  ${extendedAttributes} attribute [LegacyNullToEmptyString] CSSOMString ${attribute};`);
    }
  }
  const content = `// Generated by scripts/generate-css-style-properties.mjs.\n` +
    `[Exposed=Window]\ninterface ${interfaceName} : CSSStyleDeclaration {\n${attributes.join("\n")}\n};\n`;
  await fs.writeFile(path.join(outputDirectory, `${interfaceName}.webidl`), content);
}

import fs from "node:fs/promises";
import path from "node:path";

import syntaxPatches from "@csstools/css-syntax-patches-for-csstree" with { type: "json" };
import webref from "@webref/css";
import syntaxData from "css-tree/definition-syntax-data";

import compatibility from "../lib/jsdom/living/css/compatibility.js";
import dimensions from "../lib/jsdom/living/css/values/dimension.js";
import { descriptorContexts, descriptorOverrides } from "./css/descriptor-overrides.mjs";
import { excludedProperties, propertyOverrides } from "./css/property-overrides.mjs";
import { excludedValues, valueOverrides } from "./css/value-overrides.mjs";

const source = await webref.listAll();
const outputDirectory = path.resolve(import.meta.dirname, "../lib/generated");
await fs.mkdir(outputDirectory, { recursive: true });

function patchedSyntaxes(base, patches) {
  const result = { ...base };
  for (const [name, syntax] of Object.entries(patches)) {
    if (/^\s*\|/.test(syntax)) {
      const extension = syntax.replace(/^\s*\|\s*/, "");
      result[name] = result[name] ? `${result[name]} | ${extension}` : extension;
    } else {
      result[name] = syntax;
    }
  }
  return result;
}

function normalizeSyntax(syntax) {
  // The definition reader consumes single spaces and adjacent empty parentheses.
  return syntax.replace(/\s+/g, " ").replace(/\( \)/g, "()").trim();
}

function definition(entry, syntax = entry.syntax, property = false) {
  const result = { value: normalizeSyntax(syntax) };
  if (entry.inherited === "yes" && !entry.longhands) {
    result.inherited = true;
  }
  if (
    entry.initial &&
    (!property || !entry.longhands) &&
    !/^n\/a(?:\b|$)|^see individual properties$/i.test(entry.initial)
  ) {
    result.initial = entry.initial === "the guaranteed-invalid value" ? null : entry.initial;
  }
  if (entry.logicalPropertyGroup) {
    result.group = entry.logicalPropertyGroup;
  }
  if (entry.type) {
    result.type = entry.type;
  }
  return result;
}

function applyOverrides(target, overrides) {
  for (const [name, value] of Object.entries(overrides)) {
    if (value === undefined) {
      delete target[name];
    } else {
      target[name] = name === "value" && typeof value === "string" ? normalizeSyntax(value) : value;
    }
  }
}

async function writeData(filename, data, includeContextSensitive = false) {
  const entries = Object.keys(data)
    .sort()
    .map((name) => [name, data[name]]);
  const serialized = JSON.stringify(Object.fromEntries(entries));
  const expression = includeContextSensitive
    ? `{ ...${serialized}, ...require("../jsdom/living/css/values/context-sensitive.js") }`
    : serialized;
  await fs.writeFile(
    path.join(outputDirectory, filename),
    '"use strict";\n\n// Generated by scripts/generate-css-data.mjs from @webref/css and patched CSSTree data.\n' +
      `module.exports = ${expression};\n`,
  );
}

const properties = {};
const propertySyntaxes = patchedSyntaxes(syntaxData.properties, syntaxPatches.next.properties);
// The patched catalog still has older definitions for these properties.
for (const name of [
  "-webkit-line-clamp",
  "alignment-baseline",
  "block-ellipsis",
  "continue",
  "max-lines",
  "white-space",
]) {
  delete propertySyntaxes[name];
}
for (const property of source.properties) {
  if (
    property.syntax &&
    !compatibility.properties.aliases.has(property.name) &&
    !excludedProperties.has(property.name)
  ) {
    properties[property.name] = definition(property, propertySyntaxes[property.name], true);
  }
}
for (const [name, overrides] of Object.entries(propertyOverrides)) {
  properties[name] ??= {};
  applyOverrides(properties[name], overrides);
}
await writeData("css-property-definitions.js", properties);

const descriptors = {};
for (const context of descriptorContexts) {
  const definitions = {};
  const ruleName = context.slice(1);
  const syntaxes = patchedSyntaxes(
    syntaxData.atrules[ruleName]?.descriptors ?? {},
    syntaxPatches.next.atrules[ruleName]?.descriptors ?? {},
  );
  for (const descriptor of source.atrules.find((rule) => rule.name === context).descriptors) {
    if (descriptor.syntax && !compatibility.descriptors[context]?.aliases?.has(descriptor.name)) {
      definitions[descriptor.name] = definition(descriptor, syntaxes[descriptor.name]);
    }
  }
  for (const [name, overrides] of Object.entries(descriptorOverrides[context] ?? {})) {
    definitions[name] ??= {};
    applyOverrides(definitions[name], overrides);
  }
  descriptors[context] = definitions;
}
await writeData("css-descriptor-definitions.js", descriptors);

const values = Object.fromEntries(
  Object.entries(patchedSyntaxes(syntaxData.types, syntaxPatches.next.types)).map(
    ([name, syntax]) => [`<${name}>`, syntax],
  ),
);
// The numeric evaluator consumes the specification's two-argument structure.
delete values["<calc-size()>"];
delete values["<calc-size-basis>"];
const grammars = new Map();
for (const entry of [...source.types, ...source.functions]) {
  if (entry.syntax) {
    const name = `<${entry.name}>`;
    const entries = grammars.get(name) ?? [];
    entries.push(entry);
    grammars.set(name, entries);
  }
}
for (const [name, entries] of grammars) {
  if (
    Object.hasOwn(values, name) ||
    excludedValues.has(name) ||
    Object.hasOwn(valueOverrides, name)
  ) {
    continue;
  }
  const unscoped = entries.filter((entry) => !entry.for);
  const candidates = unscoped.length > 0 ? unscoped : entries;
  const syntaxes = new Set(candidates.map((entry) => normalizeSyntax(entry.syntax)));
  if (syntaxes.size !== 1) {
    throw new Error(`Select a webref grammar context for ${name}`);
  }
  values[name] = [...syntaxes][0];
}

// These types are defined in prose. The unit validator already defines which
// types are dimensions; the other primitives correspond directly to tokens.
for (const name of dimensions.definitions.keys()) {
  values[name] = "<dimension-token>";
}
for (const name of ["dimension", "ident", "number", "percentage", "string"]) {
  values[`<${name}>`] = `<${name}-token>`;
}
// Filter Effects specifies these bounds in prose rather than in the grammars.
// Add only the missing ranges, keeping each upstream function grammar intact.
// https://drafts.csswg.org/filter-effects-1/#supported-filter-functions
for (const name of [
  "blur",
  "brightness",
  "contrast",
  "grayscale",
  "invert",
  "opacity",
  "saturate",
  "sepia",
]) {
  const type = `<${name}()>`;
  values[type] = values[type].replace(/<(length|number|percentage)>/g, "<$1 [0,∞]>");
}

applyOverrides(values, valueOverrides);
for (const name of excludedValues) {
  values[name] = false;
}
for (const [name, syntax] of Object.entries(values)) {
  if (typeof syntax === "string") {
    values[name] = normalizeSyntax(syntax);
  }
}
await writeData("css-value-definitions.js", values, true);
